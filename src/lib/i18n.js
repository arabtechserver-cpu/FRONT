const I18nContext = createContext(null);

function normalizeLanguage(code) {
  if (code === "zh-CN") return "zh";
  return LANGUAGES.some((lang) => lang.code === code) ? code : "ar";
}

export function getSavedLanguage() {
  if (typeof window === "undefined") return "ar";
  return normalizeLanguage(localStorage.getItem(LANGUAGE_STORAGE_KEY) || "ar");
}

export function getLanguageMeta(languageCode) {
  return LANGUAGES.find((lang) => lang.code === normalizeLanguage(languageCode)) || LANGUAGES[0];
}

function getRuntimeLanguage(languageCode) {
  if (typeof window !== "undefined" && window.location.pathname.startsWith("/admin")) {
    return "ar";
  }
  return normalizeLanguage(languageCode);
}

const phraseMapCache = new Map();

export function translate(key, languageCode = "ar", values = {}) {
  const language = normalizeLanguage(languageCode);
  const template =
    dictionary[language]?.[key] ||
    (language !== "ar" ? dictionary.en[key] : undefined) ||
    dictionary.ar[key] ||
    key;
  return Object.entries(values).reduce(
    (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
    template
  );
}

function buildPhraseMap(languageCode) {
  const language = normalizeLanguage(languageCode);
  if (language === "ar") return [];
  if (phraseMapCache.has(language)) return phraseMapCache.get(language);

  const phrases = new Map();

  // Every Arabic dictionary value is a valid source phrase. Previously only
  // the smaller hand-maintained phraseKeys list was used, so text already
  // translated in the dictionary could still remain Arabic in older pages.
  Object.entries(dictionary.ar).forEach(([key, source]) => {
    if (typeof source === "string" && source && !source.includes("{")) {
      phrases.set(source, translate(key, language));
    }
  });

  Object.entries(phraseKeys).forEach(([key, variants]) => {
    variants.forEach((source) => {
      phrases.set(source, translate(key, language));
    });
  });

  Object.entries(legacyEnglishPhrases).forEach(([source, englishFallback]) => {
    if (!phrases.has(source)) phrases.set(source, englishFallback);
  });

  const phraseMap = [...phrases.entries()].sort((a, b) => b[0].length - a[0].length);
  phraseMapCache.set(language, phraseMap);
  return phraseMap;
}

function replaceKnownPhrases(value, languageCode) {
  if (!value || languageCode === "ar") return value;
  const translated = buildPhraseMap(languageCode).reduce(
    (text, [source, target]) => text.replaceAll(source, target),
    value
  );

  // Never leave a half-translated sentence. This can happen with names or
  // descriptions coming from the database: translating one known word inside
  // otherwise Arabic content produces the mixed-language text users reported.
  return /\p{Script=Arabic}/u.test(translated) && translated !== value
    ? value
    : translated;
}

function shouldSkipNode(parent) {
  return !parent || Boolean(parent.closest("[data-i18n-skip], script, style, textarea, code, pre"));
}

function applyAttributes(languageCode) {
  const attrs = ["placeholder", "title", "aria-label", "alt"];
  attrs.forEach((attr) => {
    document.querySelectorAll(`[${attr}]`).forEach((el) => {
      if (el.closest("[data-i18n-skip]")) return;
      const cacheName = `data-arabtech-original-${attr.replaceAll("-", "_")}`;
      const appliedName = `data-arabtech-applied-${attr.replaceAll("-", "_")}`;
      const currentValue = el.getAttribute(attr) || "";
      const lastAppliedValue = el.getAttribute(appliedName);

      // React may update an existing attribute after an API request. Refresh
      // the cached source when that change did not come from this translator.
      if (!el.hasAttribute(cacheName) || (
        lastAppliedValue !== null && currentValue !== lastAppliedValue
      )) {
        el.setAttribute(cacheName, currentValue);
      }
      const nextValue = replaceKnownPhrases(el.getAttribute(cacheName) || "", languageCode);
      if (currentValue !== nextValue) {
        el.setAttribute(attr, nextValue);
      }
      el.setAttribute(appliedName, nextValue);
    });
  });
}

export function applyStaticTranslations(languageCode) {
  if (typeof document === "undefined") return;
  const language = getRuntimeLanguage(languageCode);
  const meta = getLanguageMeta(language);

  document.documentElement.lang = meta.htmlLang;
  document.documentElement.dir = meta.dir;
  document.body?.setAttribute("dir", meta.dir);
  document.body?.setAttribute("data-language", language);

  const walker = document.createTreeWalker(document.documentElement, NodeFilter.SHOW_TEXT, {
    acceptNode(node) {
      const text = node.nodeValue || "";
      return !shouldSkipNode(node.parentElement) && text.trim()
        ? NodeFilter.FILTER_ACCEPT
        : NodeFilter.FILTER_REJECT;
    }
  });

  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);

  nodes.forEach((node) => {
    const currentValue = node.nodeValue || "";
    if (
      node.__arabtechOriginalText === undefined ||
      (node.__arabtechAppliedText !== undefined && currentValue !== node.__arabtechAppliedText)
    ) {
      node.__arabtechOriginalText = currentValue;
    }
    const nextValue = replaceKnownPhrases(node.__arabtechOriginalText, language);
    if (currentValue !== nextValue) node.nodeValue = nextValue;
    node.__arabtechAppliedText = nextValue;
  });

  applyAttributes(language);
}

export function I18nProvider({ children }) {
  const [language, setLanguageState] = useState("ar");

  const setLanguage = (languageCode) => {
    const nextLanguage = normalizeLanguage(languageCode);
    localStorage.setItem(LANGUAGE_STORAGE_KEY, nextLanguage);
    setLanguageState(nextLanguage);
  };

  useEffect(() => {
    const savedLanguage = getSavedLanguage();
    setLanguageState(savedLanguage);
  }, []);

  useEffect(() => {
    const runtimeLanguage = getRuntimeLanguage(language);
    let animationFrame = 0;

    const observerOptions = {
      childList: true,
      subtree: true,
      characterData: true,
      attributes: true,
      attributeFilter: ["placeholder", "title", "aria-label", "alt"]
    };

    const applyAndResume = () => {
      observer.disconnect();
      applyStaticTranslations(runtimeLanguage);
      if (document.body) observer.observe(document.body, observerOptions);
    };

    const observer = new MutationObserver(() => {
      if (animationFrame) return;
      animationFrame = window.requestAnimationFrame(() => {
        animationFrame = 0;
        applyAndResume();
      });
    });

    if (document.body) {
      applyAndResume();
    }

    return () => {
      observer.disconnect();
      if (animationFrame) window.cancelAnimationFrame(animationFrame);
    };
  }, [language]);

  useEffect(() => {
    const nativeAlert = window.alert;
    const nativeConfirm = window.confirm;
    const runtimeLanguage = getRuntimeLanguage(language);

    window.alert = (message) => nativeAlert.call(
      window,
      replaceKnownPhrases(String(message ?? ""), runtimeLanguage)
    );
    window.confirm = (message) => nativeConfirm.call(
      window,
      replaceKnownPhrases(String(message ?? ""), runtimeLanguage)
    );

    return () => {
      window.alert = nativeAlert;
      window.confirm = nativeConfirm;
    };
  }, [language]);

  const value = useMemo(() => ({
    language,
    meta: getLanguageMeta(language),
    languages: LANGUAGES,
    setLanguage,
    t: (key, values) => translate(key, language, values)
  }), [language]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (context) return context;

  return {
    language: "ar",
    meta: getLanguageMeta("ar"),
    languages: LANGUAGES,
    setLanguage: () => {},
    t: (key, values) => translate(key, "ar", values)
  };
}
